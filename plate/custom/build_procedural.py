"""Build a procedural InstaSlice index (ISQP).

A classic index stores every four-star pattern. This one stores only the
catalogue directions and, for each pattern scale, the short list of stars that
belong to each sampling circle. The pattern table is generated by the solver
the first time it is needed, in about a second, with the same fingerprint
code that reads the photograph. The file is therefore a small fraction of the
size of the table it describes, and a deeper star list costs only its stars.

Input is a table of catalogue stars: a GDR3 measurement file as used by
build_index.py, or a NumPy .npz holding the arrays ids, ra, dec (degrees,
ICRS) and mag (G).

    python build_procedural.py mid.isp.gz stars.npz --max-mag 9.65 \
        --levels 1.45 2.3 3.7 5.9 --depth 8
"""
import argparse
import gzip
import math
from pathlib import Path
import struct

import numpy as np
from scipy.spatial import cKDTree

import build_index as B


def load(path):
    if path.suffix.lower() == '.npz':
        table = np.load(path)
        data = np.zeros(len(table['mag']), dtype=B.GDR3)
        data['id'] = table['ids'].astype(np.int64)
        data['ra'], data['dec'], data['mag'] = table['ra'], table['dec'], table['mag']
        return data
    return B.catalogue(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('output', type=Path)
    parser.add_argument('source', type=Path)
    parser.add_argument('--max-mag', type=float, required=True)
    parser.add_argument('--levels', type=float, nargs='+', required=True, help='circle radii in degrees')
    parser.add_argument('--depth', type=int, nargs='+', required=True, help='stars per circle, one value or one per level')
    parser.add_argument('--dense', action='store_true', help='the star list is dense (many stars per square degree): the solver uses a tighter first test')
    args = parser.parse_args()
    depths = args.depth * len(args.levels) if len(args.depth) == 1 else args.depth
    if len(depths) != len(args.levels):
        raise SystemExit('Give one depth, or one depth per level')

    data = B.in_magnitude_order(load(args.source))
    data = data[data['mag'] <= args.max_mag]
    sky = B.directions(data)
    tree = cKDTree(sky)
    order = B.kd_order(sky)                       # implicit k-d tree: subtrees are contiguous slices
    position = np.empty(len(sky), dtype=np.uint32)
    position[order] = np.arange(len(sky), dtype=np.uint32)

    levels = []
    for radius_deg, depth in zip(args.levels, depths):
        radius = radius_deg * B.DEG
        circles = []
        for nearby in tree.query_ball_point(B.all_sky_centers(radius), 2*math.sin(radius/2), return_sorted=True):
            if len(nearby) < 4:
                continue
            ids = np.full(depth, 0xFFFFFFFF, dtype=np.uint32)
            take = min(depth, len(nearby))
            ids[:take] = position[np.array(nearby[:take])]   # brightest first: the list is in magnitude order
            circles.append(ids)
        levels.append((radius_deg, depth, np.array(circles, dtype='<u4')))
        print(f'level {radius_deg:g} deg: {len(circles):,} circles of up to {depth} stars', flush=True)

    with args.output.open('wb') as output, gzip.GzipFile(fileobj=output, filename='', mode='wb', mtime=0, compresslevel=9) as stream:
        stream.write(struct.pack('<4sIIII', b'ISQP', len(sky), len(levels), 1 if args.dense else 0, 0))
        stream.write(np.ascontiguousarray(sky[order], dtype='<f4').tobytes())
        for radius_deg, depth, circles in levels:
            stream.write(struct.pack('<fII', radius_deg, depth, len(circles)))
        for _, _, circles in levels:
            stream.write(circles.tobytes())
    print(f'{args.output.name}: {len(sky):,} stars, {args.output.stat().st_size/1048576:.1f} MiB', flush=True)


if __name__ == '__main__':
    main()
